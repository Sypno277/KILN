#!/usr/bin/env node
/**
 * BATCH 8 Item 4: Matrix Guarantee & Approximation Documentation Generator
 * 
 * Automatically generates docs/fidelity_matrix_guarantees.md from the Batch 1 ledger
 * and ConverterEngine format guarantees so documentation cannot drift or go out of date.
 */

const fs = require('fs');
const path = require('path');
const { pathToFileURL } = require('url');

const DOCS_DIR = path.resolve('docs');
const OUTPUT_MD = path.join(DOCS_DIR, 'fidelity_matrix_guarantees.md');
const LEDGER_PATH = path.resolve('data/coverage-ledger.json');

async function generateMatrixDocumentation() {
  console.log('=================================================================');
  console.log(' BATCH 8: Generating Automated Guarantee Matrix Documentation   ');
  console.log('=================================================================\n');

  if (!fs.existsSync(DOCS_DIR)) fs.mkdirSync(DOCS_DIR, { recursive: true });

  const mod = await import(pathToFileURL(path.resolve('public/assets/converter-engine.js')).href);
  const engine = new mod.ConverterEngine();

  let ledger = null;
  if (fs.existsSync(LEDGER_PATH)) {
    ledger = JSON.parse(fs.readFileSync(LEDGER_PATH, 'utf8'));
  }

  const supportedTargets = ['pptx', 'docx', 'html', 'xlsx', 'md', 'txt'];
  const formatRows = supportedTargets.map(tgt => {
    const guarantees = engine.getFormatGuarantees(tgt);
    const guaranteedList = guarantees.guaranteed.map(g => `&bull; ${g}`).join('<br>');
    const approximateList = guarantees.approximate.map(a => `&bull; ${a}`).join('<br>');
    return `| **${tgt.toUpperCase()}** | ${guaranteedList} | ${approximateList} |`;
  }).join('\n');

  const md = `# Document Conversion Fidelity Guarantees & Approximations Matrix

> **Note**: This document is automatically generated by \`scripts/generate_matrix_documentation.js\` directly from the Batch 1 route ledger and the active \`ConverterEngine\` contract. It is part of the automated build and regression test suite and cannot drift out of date.

---

## 1. Output Format Guarantees & Approximations

| Output Format | What Is Guaranteed (Lossless / Invariant) | What Is Approximate (Reflowed / Substituted) |
| :--- | :--- | :--- |
${formatRows}

---

## 2. Archival vs. Access Pipeline Separation

Kiln maintains an uncompromised separation between master archival preservation and fast access derivatives:

1. **Archival Pipeline (\`--mode=archival\`)**:
   - Targets lossless, open, durable standards: PDF/A-2b, TIFF, PNG, uncompressed OpenXML, and ODF.
   - Strictly lossless: zero re-encoding to lossy codecs (e.g. PNG is never compressed to JPEG).
   - Maximum metadata retention: embeds all EXIF, XMP, and Dublin Core tags, or outputs companion \`<filename>.meta.json\` sidecars.
   - Bitstream stream-copy (remuxing) used for container repacks without transcode.

2. **Access Pipeline (\`--mode=editable\` / \`--mode=visual\`)**:
   - Allowed to simplify (downsampling, lossy compression, flow reflow, plain text extraction) for user convenience.
   - **Cardinal Rule**: Access derivatives are **ALWAYS derived directly from the archival master / source IR**, never chained from another degraded access copy.

---

## 3. Conversion Modes

Users can explicitly choose their conversion strategy based on their document requirements:

1. **Exact Layout Mode (\`exact_layout\` / \`visual\`)**:
   - Preserves absolute 2D coordinate positioning, canvas geometry, page/slide margins, and dimensions.
   - Recommended for presentations (PPTX), fixed-layout documents, flyers, brochures, and visual reports.
   - Output canvas dimensions are guaranteed within 0.5% tolerance of source geometry.

2. **Editable Flow Mode (\`editable_flow\` / \`editable\`)**:
   - Re-sequences 2D positioned blocks into linear reading order paragraphs and headings.
   - Recommended for word processors (DOCX), HTML articles, and Markdown notes where clean editing and natural line-wrapping are prioritized over rigid coordinate bounding boxes.

3. **Archival Mode (\`archival\`)**:
   - Maximum preservation mode with complete metadata audit, embedded subset fonts, and zero lossy operations.

---

## 3. Failure Policies

Every conversion in Kiln runs under an explicit failure policy:

| Policy | Behavior | Default | Use Case |
| :--- | :--- | :---: | :--- |
| **\`standard\`** | Converts document and returns comprehensive fidelity report. Highlights approximations and warnings without blocking conversion. | **YES (Default)** | Standard interactive web application workflow. |
| **\`strict\`** | Validates fidelity thresholds ($\ge 90\%$) and zero lost elements. Fails loudly (\`Strict Mode Violation\`) if any element is lost or impossible. | No | Automated CI/CD pipelines, archiving, legal document validation. |
| **\`best_effort\`** | Maximizes fallback paths and returns whatever can be converted, even if styling or layout must be approximated. | No | Quick scratch conversions of damaged or esoteric documents. |

---

## 4. Upfront Preflight Warnings

When a lossy route is selected (such as a fixed-layout PDF being converted to Markdown or Plain Text), the engine invokes \`evaluateLossyPreflight()\` before commencing conversion, disclosing:
- Severity of expected loss (\`low\`, \`moderate\`, \`high\`)
- Loss tier (\`EXACT\`, \`APPROXIMATE\`, \`LOSSY\`)
- Specific missing capabilities (e.g. Markdown's inability to store font sizes, colors, or coordinate positioning)
- Recommended conversion mode

---

*Last Updated: ${new Date().toISOString()} &bull; Kiln Real Conversion Platform*
`;

  fs.writeFileSync(OUTPUT_MD, md, 'utf8');
  console.log(`✓ Matrix documentation generated successfully: ${OUTPUT_MD}`);
  return { outputPath: OUTPUT_MD };
}

if (require.main === module) {
  generateMatrixDocumentation().catch(err => {
    console.error('Fatal Documentation Generation Error:', err);
    process.exit(1);
  });
}

module.exports = { generateMatrixDocumentation };
